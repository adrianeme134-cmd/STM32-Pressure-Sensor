void I2C_WHO_AM_I(void *argument) {

	for(;;) {

		   // pointer to a constant character/string
		    // This  declares an uninitialized  pointer where our message will be stored
		    const char *uart_message2;

		    uint8_t recieved_byte;

		    // Driving CS high to select I2C
		    HAL_GPIO_WritePin(I2C_CS_ENABLE_GPIO_Port, I2C_CS_ENABLE_Pin, GPIO_PIN_SET);

		    // I2C_MEMADD_SIZE_8BIT tells us how wide the internal register is, ONE_BYTE TELLS US HOW MANY BYTES WE HAVE TO SEND AS WE CAN ONLY SEND OUT 1 BYTE AT A TIME
		     HAL_I2C_Mem_Read(&hi2c1, PRESSURE_SENSOR_DEVICE_ADDRESS,0x0F,I2C_MEMADD_SIZE_8BIT,&recieved_byte,ONE_BYTE,100);



		    if(recieved_byte == 0xB3) {

		    	// since uart_message2 is a pointer, this says store the first address of the first character string in uart_message2 with the NULL character terminator at the end
		    	uart_message2 = "RECIEVED 0xB3 \r\n";

		    } else

		    	uart_message2 = "DID NOT RECIEVE 0xB3 \r\n";



		    HAL_UART_Transmit(&huart2, uart_message2, strlen(uart_message2), 100);




	}
}



